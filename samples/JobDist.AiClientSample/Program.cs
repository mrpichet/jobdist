// =============================================================================================
// AI client sample: connect to the JobDist MCP endpoint, discover the tools (each one arrives as a
// Microsoft.Extensions.AI AIFunction), call the risk / anomaly tools directly, then show how to hand
// the same tools to any IChatClient so an LLM calls them automatically.
//
// Usage: dotnet run --project samples/JobDist.AiClientSample -- [http://localhost:8080/mcp] [api-key] [jobType]
// =============================================================================================
using Microsoft.Extensions.AI;
using ModelContextProtocol;
using ModelContextProtocol.Client;
using ModelContextProtocol.Protocol;

var endpoint = new Uri(args.ElementAtOrDefault(0) ?? "http://localhost:8080/mcp");
var apiKey = args.ElementAtOrDefault(1) ?? Environment.GetEnvironmentVariable("JOBDIST_AI_KEY") ?? "dev-ai-agent-key-change-me";
var jobType = args.ElementAtOrDefault(2) ?? "image.resize";

// Step 1: connect over Streamable HTTP; the API key must have the AiAgent role.
var transport = new HttpClientTransport(new HttpClientTransportOptions
{
    Endpoint = endpoint,
    Name = "JobDist",
    AdditionalHeaders = new Dictionary<string, string> { ["X-Api-Key"] = apiKey }
});
await using var mcp = await McpClient.CreateAsync(transport);

// Step 2: list tools. Each McpClientTool *is* an AIFunction (Microsoft.Extensions.AI) with a JSON schema.
IList<McpClientTool> tools = await mcp.ListToolsAsync();
Console.WriteLine($"{tools.Count} tools exposed by JobDist:");
foreach (var tool in tools)
{
    Console.WriteLine($" - {tool.Name}");
}

// Step 3: call tools directly (no LLM needed).
await PrintAsync("get_cluster_summary", new Dictionary<string, object?>());
await PrintAsync("assess_submission_risk", new Dictionary<string, object?> { ["jobType"] = jobType, ["priority"] = 80 });
await PrintAsync("recommend_workers", new Dictionary<string, object?> { ["jobType"] = jobType, ["top"] = 3 });
await PrintAsync("detect_anomalies", new Dictionary<string, object?> { ["windowMinutes"] = 60 });

// Step 4: give the tools to an LLM. Any IChatClient works (Azure OpenAI, OpenAI, Ollama, Foundry Local, Anthropic ...):
//
//   IChatClient chat = new ChatClientBuilder(innerChatClient)   // innerChatClient from your provider package
//       .UseFunctionInvocation()                                // runs the tool calls the model asks for
//       .Build();
//   var answer = await chat.GetResponseAsync(
//       "Is it safe to submit 500 image.resize jobs now? Which workers would get them and are there anomalies?",
//       new ChatOptions { Tools = [.. tools] });
//   Console.WriteLine(answer.Text);
//
// The model sees the JSON schemas generated by AIFunctionFactory on the server, decides which tools to call,
// FunctionInvokingChatClient invokes them through MCP and feeds the results back to the model.
ChatOptions options = new() { Tools = [.. tools] };
Console.WriteLine($"ChatOptions prepared with {options.Tools.Count} AI tools.");

// Calls one tool and prints its text content.
async Task PrintAsync(string name, Dictionary<string, object?> arguments)
{
    Console.WriteLine($"\n== {name}");
    try
    {
        var result = await mcp.CallToolAsync(name, arguments);
        foreach (var block in result.Content.OfType<TextContentBlock>())
        {
            Console.WriteLine(block.Text.Length > 1500 ? block.Text[..1500] + " ..." : block.Text);
        }
    }
    catch (McpException ex)
    {
        Console.WriteLine($"Tool error: {ex.Message}");
    }
}
